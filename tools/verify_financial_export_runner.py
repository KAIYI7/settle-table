"""Run the loopback demo while recording only its mock Notion output."""
import json
import os
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from settletable.notion import MockNotionClient

output = Path(os.environ["SETTLETABLE_MOCK_CAPTURE"])
for method in ("create_page", "append_block_children"):
    original = getattr(MockNotionClient, method)

    def capture(self, *args, _original=original, **kwargs):
        result = _original(self, *args, **kwargs)
        output.write_text(json.dumps({"pages": self.pages, "blocks": self.blocks}), encoding="utf-8")
        return result

    setattr(MockNotionClient, method, capture)

from tools import run_demo

# This test-only endpoint proves the process that owns the loopback listener
# has the unique token generated by its caller, even if a port probe races.
make_server = run_demo.make_server

def make_owned_server(host, port, app):
    def owned_app(environ, start_response):
        if environ.get("PATH_INFO") == "/__financial_test_owner__":
            start_response("200 OK", [("Content-Type", "text/plain")])
            return [os.environ["SETTLETABLE_TEST_OWNER"].encode("ascii")]
        return app(environ, start_response)
    return make_server(host, port, owned_app)

run_demo.make_server = make_owned_server

if __name__ == "__main__":
    run_demo.main()
